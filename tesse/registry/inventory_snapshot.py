"""Read the operational SQL rows on a private image, never through SQLite on the source."""

import errno
import json
import os
import sqlite3
import stat
import sys
import time
from contextlib import ExitStack, closing
from pathlib import Path

from ..filelocks import lock_bytes

# Default SQLite OS VFS: pending byte, shared range (other readers remain
# welcome) and WAL-index writer/checkpointer/dead-man switch bytes. See
# SQLite's lockingv3.html, walformat.html and src/os_unix.c / src/os_win.c.
_PENDING = 0x40000000
_WAL_WRITE = 120
_WAL_DMS = 128


class SnapshotBusy(Exception):
    pass


def _open_read(stack, path):
    if not stat.S_ISREG(path.lstat().st_mode):
        raise ValueError("a origem e seus auxiliares devem ser arquivos regulares")
    flags = os.O_RDONLY
    for flag in ("O_NONBLOCK", "O_NOFOLLOW", "O_BINARY"):
        flags |= getattr(os, flag, 0)
    try:
        fd = os.open(path, flags | getattr(os, "O_NOATIME", 0))
    except PermissionError:
        fd = os.open(path, flags)
    stack.callback(os.close, fd)
    if not stat.S_ISREG(os.fstat(fd).st_mode):
        raise ValueError("a origem e seus auxiliares devem ser arquivos regulares")
    return fd


def _shared_lock(fd, offset, length=1):
    try:
        lock_bytes(fd, offset, length)
    except OSError as exc:
        if exc.errno in (errno.EACCES, errno.EAGAIN):
            raise SnapshotBusy from exc
        raise


def _copy(fd, path, deadline):
    with path.open("wb") as out:
        while chunk := os.read(fd, 1024 * 1024):
            if time.monotonic() >= deadline:
                raise SnapshotBusy
            out.write(chunk)


def _same_file(path, fd):
    try:
        return os.path.samestat(path.lstat(), os.fstat(fd))
    except FileNotFoundError:
        return False


def _wal_frontier(fd):
    # SQLite's two 48-byte WalIndexHdr copies must agree. The first
    # committed frame number, page count, frame checksum, and salts are
    # regenerated by SQLite when the copied WAL is recovered.
    header = os.read(fd, 96)
    if len(header) != 96 or header[:48] != header[48:] or header[12] != 1:
        raise ValueError("índice do WAL não confirmado")
    return header[16:40] if any(header[16:20]) else b""


def _capture(source, target, deadline):
    wal = source.with_name(source.name + "-wal")
    shm = source.with_name(source.name + "-shm")
    journal = source.with_name(source.name + "-journal")
    wal_copy = target.with_name(target.name + "-wal")
    wal_copy.unlink(missing_ok=True)
    frontier = None
    with ExitStack() as files:
        database_fd = _open_read(files, source)
        _shared_lock(database_fd, _PENDING)
        _shared_lock(database_fd, _PENDING + 2, 510)
        # A rollback journal may need recovery. Never treat the main file in
        # isolation as committed in that case.
        if os.path.lexists(journal):
            raise SnapshotBusy
        if os.path.lexists(wal):
            # The DB lock excludes last-close cleanup and journal-mode changes.
            # Freeze WAL appends/resets and all checkpoints while copying.
            try:
                shm_fd = _open_read(files, shm)
                _shared_lock(shm_fd, _WAL_DMS)
                _shared_lock(shm_fd, _WAL_WRITE, 2)
                wal_fd = _open_read(files, wal)
            except FileNotFoundError as exc:
                raise SnapshotBusy from exc
            if os.fstat(wal_fd).st_size:
                frontier = _wal_frontier(shm_fd)
            _copy(database_fd, target, deadline)
            _copy(wal_fd, wal_copy, deadline)
            if not (_same_file(shm, shm_fd) and _same_file(wal, wal_fd)):
                raise SnapshotBusy
        else:
            _copy(database_fd, target, deadline)
            # A first connection could create the WAL; the DB lock prevents
            # SQLite from removing it again until we release the lock.
            if os.path.lexists(wal):
                raise SnapshotBusy
        if not _same_file(source, database_fd) or os.path.lexists(journal):
            raise SnapshotBusy
    return frontier


def _fetch(db, sql):
    return [dict(row) for row in db.execute(sql)]


def _read_copy(path, frontier=None):
    # SQLite may rebuild shared memory/recover WAL here, only in the scratch
    # directory; both SELECTs see one transaction on the captured image.
    with closing(sqlite3.connect(path.as_uri() + "?mode=rw", uri=True)) as db:
        db.row_factory = sqlite3.Row
        db.execute("PRAGMA query_only = ON")
        db.execute("PRAGMA trusted_schema = OFF")
        db.execute("BEGIN")
        required = {"model_metadata", "active_pointers"}
        if required != {r[0] for r in db.execute("""SELECT name FROM sqlite_schema
                WHERE name IN ('model_metadata', 'active_pointers') AND type = 'table'""")}:
            raise ValueError("esquema do Store incompatível")
        if frontier is not None:
            with ExitStack() as files:
                shm_fd = _open_read(files, path.with_name(path.name + "-shm"))
                if _wal_frontier(shm_fd) != frontier:
                    raise ValueError("o WAL recuperado não corresponde ao último commit da origem")
        return {
            "models": _fetch(db, """SELECT system_id, system_version, model_id, model_version,
                asset, timeframe, status FROM model_metadata ORDER BY asset, model_id, model_version"""),
            "pointers": _fetch(db, """SELECT asset, model_id, model_version FROM active_pointers
                ORDER BY asset"""),
        }


def _snapshot(source, target):
    if os.name not in {"posix", "nt"}:
        raise ValueError("VFS padrão do SQLite não suportado nesta plataforma")
    deadline = time.monotonic() + 2
    while time.monotonic() < deadline:
        try:
            frontier = _capture(source, target, deadline)
        except SnapshotBusy:
            time.sleep(0.025)
        else:
            return _read_copy(target, frontier)
    raise ValueError("não foi possível obter uma visão consistente no prazo")


def _main(source, target):
    # Separate process: POSIX locks can be implicitly dropped by closing any
    # descriptor to the inode in the same process (including a Store handle).
    try:
        result = _snapshot(Path(source), Path(target))
        print(json.dumps(result))
    except (sqlite3.Error, OSError, TypeError, ValueError) as exc:
        print(json.dumps({"error": f"leitura segura do Store falhou: {exc}"}))


if __name__ == "__main__":
    _main(*sys.argv[1:])
